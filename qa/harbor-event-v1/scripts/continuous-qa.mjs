import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL, fileURLToPath} from 'node:url';
import {launchBrowser} from '../../playwright-runtime.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../..');
const qa=path.join(root,'qa/harbor-event-v1/continuous');
fs.mkdirSync(qa,{recursive:true});
const browser=await launchBrowser();
const context=await browser.newContext({viewport:{width:1920,height:1080}});
const page=await context.newPage();
const errors=[];
const external=[];
const checks=[];
const check=(name,pass,detail='')=>{checks.push({name,passed:!!pass,detail});console.log(`${pass?'PASS':'FAIL'} ${name}${detail?' — '+detail:''}`);};
page.on('pageerror',error=>errors.push(error.message));
page.on('requestfailed',request=>errors.push(request.url()+' '+request.failure()?.errorText));
page.on('request',request=>{if(/^https?:/i.test(request.url()))external.push(request.url());});
await context.setOffline(true);
await page.goto(pathToFileURL(path.join(root,'效果查看/index.html')).href,{waitUntil:'load'});
check('Standalone file opens offline',(await page.locator('#event').getAttribute('data-phase'))==='waiting');
await page.locator('#waitButton').click();
await page.waitForTimeout(6800);
check('Letter event still unfolds',(await page.locator('#event').getAttribute('data-phase'))==='revealed');
await page.locator('#acceptButton').click();
check('Accepting letter opens the blank transition',await page.locator('#handoff').isVisible()&&!(await page.locator('#event').isVisible()));
check('Transition only exposes the continuation button',(await page.locator('button:visible').count())===1);
check('Continuation receives keyboard focus',await page.locator('#continueButton').evaluate(el=>el===document.activeElement));
await page.screenshot({path:path.join(qa,'01-blank-transition-1920x1080.png')});
await page.keyboard.press('Enter');
const frame=page.frameLocator('#prototypeFrame');
await frame.locator('[data-screen="mission"]').waitFor({state:'visible'});
let runtime=page.frames().find(item=>item.parentFrame());
check('Continuation opens original second page',(await runtime.evaluate(()=>window.__tidalPost.getState().screen))==='mission');
check('Original commission information is preserved',(await frame.locator('#missionTitle').textContent()).trim()==='蓝潮岛的回信');
await page.screenshot({path:path.join(qa,'02-original-mission-1920x1080.png')});
await frame.locator('[data-action="mission-back"]').click();
await page.locator('#event').waitFor({state:'visible'});
check('Mission return reconnects to the new Harbor',await page.locator('#event').isVisible());
await page.locator('#acceptButton').click();
await page.locator('#continueButton').click();
await frame.locator('[data-screen="mission"]').waitFor({state:'visible'});
check('Re-entering keeps one embedded prototype',(await page.locator('iframe').count())===1);
await frame.locator('[data-action="mission-primary"]').click();
await frame.locator('[data-item="blue-envelope"]').click();
await frame.locator('[data-action="save-mailbag"]').click();
check('Mailbag selection and save work',await runtime.evaluate(()=>window.__tidalPost.getState().mailbagSaved));
await page.screenshot({path:path.join(qa,'03-original-mailbag-1920x1080.png')});
await frame.locator('[data-action="go-map"]').click();
await runtime.waitForFunction(()=>window.__tidalPost.reveal()?.active===true);
await page.waitForTimeout(400);
await page.keyboard.press('Enter');
await runtime.waitForFunction(()=>document.querySelector('[data-screen="map"]').dataset.mapPhase==='MAP_READY');
check('Map reveal and planning work',await runtime.evaluate(()=>window.__tidalRoute.getState().valid));
await page.screenshot({path:path.join(qa,'04-original-map-1920x1080.png')});
await frame.locator('#confirm-route').click();
await frame.locator('[data-action="start-sailing"]').click();
await runtime.waitForFunction(()=>window.__tidalPost.getState().screen==='sailing');
check('Map confirmation enters sailing',await frame.locator('#sailingCanvas').isVisible());
await page.screenshot({path:path.join(qa,'05-original-sailing-1920x1080.png')});
await runtime.evaluate(()=>window.__tidalPost.sailing.control('throttle-up',true));
await runtime.waitForFunction(()=>window.__tidalPost.sailing.getState().readyToDeliver===true,null,{timeout:45000});
await runtime.evaluate(()=>{window.__tidalPost.sailing.control('throttle-up',false);window.__tidalPost.sailing.tryDeliver();});
await frame.locator('[data-screen="result"]').waitFor({state:'visible'});
await frame.locator('[data-action="claim-reward"]').click();
check('Delivery result and reward work',await runtime.evaluate(()=>window.__tidalPost.getState().stamps===160));
await page.screenshot({path:path.join(qa,'06-original-result-1920x1080.png')});
await frame.locator('[data-action="return-harbor"]').click();
await page.locator('#event').waitFor({state:'visible'});
check('Full loop returns to Harbor with updated balance',(await page.locator('.postage strong').textContent()).trim()==='160');
await page.locator('#acceptButton').click();
await page.setViewportSize({width:1366,height:768});
check('Transition fits 1366×768',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth&&document.documentElement.scrollHeight<=innerHeight));
await page.screenshot({path:path.join(qa,'07-blank-transition-1366x768.png')});
await page.locator('#continueButton').click();
await frame.locator('[data-screen="mission"]').waitFor({state:'visible'});
await page.screenshot({path:path.join(qa,'08-original-mission-1366x768.png')});
const broken=await runtime.evaluate(()=>[...document.images].filter(img=>!img.complete||img.naturalWidth===0).map(img=>img.alt||img.src.slice(0,90)));
check('All embedded images load',broken.length===0,broken.join(' | '));
check('No network or runtime dependencies',errors.length===0&&external.length===0,JSON.stringify({errors,external}));
await browser.close();
const report={checks,passed:checks.filter(c=>c.passed).length,failed:checks.filter(c=>!c.passed).length,errors,external};
fs.writeFileSync(path.join(qa,'qa-report.json'),JSON.stringify(report,null,2));
console.log(`RESULT ${report.passed}/${checks.length} passed`);
if(report.failed)process.exitCode=1;
